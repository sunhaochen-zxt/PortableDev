using System.Text;
using PortableDev.Core.Model;

namespace PortableDev.Core;

/// <summary>
/// Renders a <c>[[launch]]</c> entry into the batch file that sits at the stick root.
///
/// Everything the launcher needs is expressed relative to <c>%~dp0</c>, so it keeps working
/// after a drive-letter change and does not depend on the C:\Dev junction existing: a
/// launcher is a stick artifact, exactly like the tools it starts.
///
/// Generated on purpose, not hand-written: the version is part of the path
/// (<c>tools\tabby\1.0.238\Tabby.exe</c>), and a hand-written launcher pins a second copy
/// of that version that goes stale the moment the manifest is bumped.
/// </summary>
public static class LaunchWriter
{
    /// <summary>Path of the generated launcher inside the stick root.</summary>
    public static string Path(string stickRoot, LaunchSpec spec)
        => System.IO.Path.Combine(stickRoot, spec.Name + ".cmd");

    /// <summary>Relative directory of the tool, e.g. <c>tools\tabby\1.0.238</c>.</summary>
    private static string ToolDir(ToolManifest tool)
        => PathResolver.ToolRelativeDir(tool).Replace('/', '\\');

    public static string Render(LaunchSpec spec, ToolManifest tool, PathResolver resolver)
    {
        var toolDir = ToolDir(tool);
        var exePath = toolDir + "\\" + spec.Exe.Replace('/', '\\');

        var workDir = spec.Dir == "." || string.IsNullOrWhiteSpace(spec.Dir)
            ? toolDir
            : toolDir + "\\" + spec.Dir.Replace('/', '\\').TrimEnd('\\');

        var sb = new StringBuilder();
        sb.Append("@echo off\r\n");
        sb.Append("rem Generated by PortableDev from manifest\\manifest.d\\")
          .Append(tool.Tool.Id)
          .Append(".toml - do not edit; change the manifest and run apply.\r\n");
        sb.Append("rem   ")
          .Append(tool.Tool.Id).Append(' ').Append(tool.Tool.Version)
          .Append("  ->  ").Append(exePath).Append("\r\n");
        if (!string.IsNullOrWhiteSpace(spec.Notes))
            sb.Append("rem   ").Append(spec.Notes!.Replace("\r", " ").Replace("\n", " ")).Append("\r\n");
        sb.Append("setlocal\r\n");

        foreach (var e in spec.Env)
            sb.Append("set \"").Append(e.Name).Append('=').Append(Expand(e.Value, tool, resolver)).Append("\"\r\n");

        sb.Append("start \"\" /d \"%~dp0").Append(workDir).Append("\" \"%~dp0").Append(exePath).Append('"');

        foreach (var arg in spec.Args)
            sb.Append(' ').Append(Quote(Expand(arg, tool, resolver)));

        sb.Append("\r\n");
        return sb.ToString();
    }

    /// <summary>
    /// <c>{{STICK}}</c> is the launcher's own directory, so a profile path can stay
    /// relative; everything else expands through the resolver as usual.
    /// </summary>
    private static string Expand(string value, ToolManifest tool, PathResolver resolver)
        => resolver.Expand(value.Replace("{{STICK}}", "%~dp0", StringComparison.OrdinalIgnoreCase), tool);

    /// <summary>
    /// Only quote what needs it: a path with a space, or an empty argument. A value that
    /// still holds <c>%~dp0</c> is always quoted, because the directory the launcher ends up
    /// in is unknown at generation time and may well contain a space.
    /// </summary>
    private static string Quote(string value)
    {
        if (value.Length == 0) return "\"\"";
        if (value.Contains("%~dp0", StringComparison.Ordinal) ||
            value.IndexOfAny(new[] { ' ', '\t', '"', '&', '|', '<', '>' }) >= 0)
            return "\"" + value.Replace("\"", "\"\"") + "\"";
        return value;
    }
}

using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using PortableDev.Core.Util;

namespace PortableDev.Core.Identity;

/// <summary>
/// The stick's identity: `pd-<12 hex>` derived from volume serial + label, persisted in
/// `state\\stick.json` (kernel.md 4.4). Drive letters never participate, so moving the stick
/// between machines or letters keeps the id stable.
/// </summary>
public sealed partial class StickIdentity
{
    private StickIdentity(string stickId, string source, string volumeSerial, string label)
    {
        StickId = stickId;
        Source = source;
        VolumeSerial = volumeSerial;
        Label = label;
    }

    public string StickId { get; }

    /// <summary>`volume` (derived on first run), `manual` (regenerated by doctor), or `fallback`.</summary>
    public string Source { get; }

    public string VolumeSerial { get; }

    public string Label { get; }

    public const string RelativePath = @"state\stick.json";

    [GeneratedRegex("^pd-[0-9a-f]{12}$")]
    private static partial Regex StickIdPattern();

    /// <summary>Computes the deterministic id for a volume; used both by the kernel and by `pd.exe`.</summary>
    public static string ComputeId(uint serial, string label)
        => "pd-" + Sha256Util.HexLower($"portabledev:{serial:X8}:{label}")[..12];

    /// <summary>Reads the id, or derives and persists it when the file is absent or unreadable.</summary>
    public static StickIdentity LoadOrCreate(string stickRoot, bool persist = true)
    {
        var path = Path.Combine(stickRoot, RelativePath);
        if (File.Exists(path))
        {
            try
            {
                var node = JsonNode.Parse(File.ReadAllText(path)) as JsonObject;
                var id = JsonUtil.String(node, "stickId");
                if (id is not null && StickIdPattern().IsMatch(id))
                {
                    return new StickIdentity(
                        id,
                        JsonUtil.String(node, "source") ?? "volume",
                        JsonUtil.String(node, "volumeSerial") ?? string.Empty,
                        JsonUtil.String(node, "label") ?? string.Empty);
                }
            }
            catch (Exception ex) when (ex is IOException or System.Text.Json.JsonException)
            {
                // Corrupt identity is treated as missing; we regenerate below and log by the caller.
            }
        }

        if (VolumeReader.TryRead(stickRoot, out var info, out var error) && info is not null)
        {
            var identity = new StickIdentity(ComputeId(info.Serial, info.Label), "volume", info.SerialHex, info.Label);
            if (persist)
            {
                Save(stickRoot, identity);
            }

            return identity;
        }

        // Last resort: derive from the volume label + a stable machine-independent salt. Only happens on
        // exotic file systems; the id is documented as `fallback` so `pd doctor` can flag it.
        var fallback = new StickIdentity(
            "pd-" + Sha256Util.HexLower($"portabledev:fallback:{stickRoot}")[..12],
            "fallback",
            string.Empty,
            string.Empty);
        _ = error;
        if (persist)
        {
            Save(stickRoot, fallback);
        }

        return fallback;
    }

    public static void Save(string stickRoot, StickIdentity identity)
    {
        var document = new JsonObject
        {
            ["schema"] = 1,
            ["stickId"] = identity.StickId,
            ["source"] = identity.Source,
            ["volumeSerial"] = identity.VolumeSerial,
            ["label"] = identity.Label,
            ["createdAt"] = TimeUtil.NowIso(),
        };

        AtomicFile.WriteAllText(Path.Combine(stickRoot, RelativePath), document.ToJsonString());
    }
}
